def linear_proj(indices: list[int], weights: list[float]) -> dict:
    return {"obs_mode": "linear_proj", "obs_params": {"indices": list(indices), "weights": list(weights), "normalize": True}}


def twoscale_local_mix(K: int, J: int, slow_terms: list[tuple[int, float]], fast_group: int = 0, fast_weight: float = 0.2) -> dict:
    indices = [idx for idx, _ in slow_terms]
    weights = [w for _, w in slow_terms]
    fast_offset = K + fast_group * J
    indices.extend(range(fast_offset, fast_offset + J))
    weights.extend([fast_weight / J] * J)
    return linear_proj(indices, weights)


def task(name: str, system: str, *, family: str = "", regime: str = "", tags: tuple[str, ...] = (), **kwargs) -> BenchmarkTask:
    return BenchmarkTask(
        name=name,
        system=system,
        family=family or system,
        regime=regime,
        tags=tags,
        **kwargs,
    )


